-- RescueCoordinationService : missions de sauvetage et historique des evenements.

CREATE TABLE mission (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id      VARCHAR(40)      NOT NULL,
    report_id       BIGINT           NOT NULL,
    status          VARCHAR(20)      NOT NULL,
    intervenant_id  BIGINT,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    severity        INT              NOT NULL,
    species         VARCHAR(50),
    reassignments   INT              NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_at     TIMESTAMP WITH TIME ZONE,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    -- RM04 : verrou optimiste, la premiere acceptation validee gagne
    version         BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT uk_mission_mission_id UNIQUE (mission_id),
    CONSTRAINT uk_mission_report UNIQUE (report_id)
);

-- RM05 : recherche des missions attribuees sans reponse
CREATE INDEX idx_mission_status_assigned ON mission (status, assigned_at);

CREATE TABLE mission_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id      BIGINT       NOT NULL REFERENCES mission (id),
    type            VARCHAR(20)  NOT NULL,
    intervenant_id  BIGINT,
    message         VARCHAR(500),
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_mission_event_mission ON mission_event (mission_id);
