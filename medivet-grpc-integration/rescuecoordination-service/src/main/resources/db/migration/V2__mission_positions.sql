-- Client streaming TrackMission : positions GPS envoyees par l'intervenant pendant son trajet.

CREATE TABLE mission_position (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id      BIGINT           NOT NULL REFERENCES mission (id),
    intervenant_id  BIGINT           NOT NULL,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    recorded_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_mission_position_mission ON mission_position (mission_id, recorded_at);
