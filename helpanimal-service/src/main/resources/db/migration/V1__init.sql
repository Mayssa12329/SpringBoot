-- HelpAnimalService : schema initial (compatible PostgreSQL et H2 en mode PostgreSQL)

CREATE TABLE report (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species          VARCHAR(50)      NOT NULL,
    category         VARCHAR(30)      NOT NULL,
    description      VARCHAR(2000)    NOT NULL,
    severity         INT              NOT NULL,
    photo_url        VARCHAR(500)     NOT NULL,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    status           VARCHAR(20)      NOT NULL,
    reporter_id      BIGINT           NOT NULL,
    assignee_id      BIGINT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    taken_charge_at  TIMESTAMP WITH TIME ZONE,
    version          BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT ck_report_severity CHECK (severity BETWEEN 1 AND 5)
);

CREATE INDEX idx_report_status ON report (status);
CREATE INDEX idx_report_position ON report (latitude, longitude);

CREATE TABLE report_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id    BIGINT       NOT NULL REFERENCES report (id),
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    actor_id     BIGINT       NOT NULL,
    comment      VARCHAR(1000),
    changed_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_history_report ON report_status_history (report_id);

CREATE TABLE mission_assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id       BIGINT       NOT NULL REFERENCES report (id),
    mission_id      VARCHAR(100) NOT NULL,
    intervenant_id  BIGINT       NOT NULL,
    assigned_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_mission_report UNIQUE (report_id)
);

CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action       VARCHAR(50)   NOT NULL,
    target_type  VARCHAR(50)   NOT NULL,
    target_id    BIGINT        NOT NULL,
    actor_id     BIGINT        NOT NULL,
    details      VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
